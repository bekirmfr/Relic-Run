/*
 * Relic Run content extractor
 * ---------------------------
 * Parses .port/Daily Delve.dc.html and .port/strings.js and emits the game's
 * content tables as JSON into Tools/out/, ready for the Unity ScriptableObject
 * importer (Phase 8 of docs/port-plan.md).
 *
 * The source data lives in plain JS object literals, so we brace-match each
 * declaration and evaluate it in a sandboxed vm rather than regexing it. A few
 * tables carry closures (event outcomes, achievement predicates); those are
 * serialized as { __fn: "<source>" } so the port has the exact logic to read,
 * and are flagged in the manifest as needing a hand-written C# counterpart.
 *
 * Re-runnable: delete Tools/out and run `node Tools/extract/extract.mjs`.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PORT = join(ROOT, ".port");
const OUT = join(ROOT, "Tools", "out");
const SRC = readFileSync(join(PORT, "Daily Delve.dc.html"), "utf8");
const STRINGS_SRC = readFileSync(join(PORT, "strings.js"), "utf8");

/* ---------- helpers ---------- */

const warnings = [];
const warn = (m) => { warnings.push(m); console.warn("  ! " + m); };

/** Brace/bracket-match a top-level `const NAME = <literal>` and return its source text. */
function literalOf(name) {
  const decl = new RegExp(`\\bconst ${name}\\s*=\\s*`).exec(SRC);
  if (!decl) throw new Error(`declaration not found: ${name}`);
  let i = decl.index + decl[0].length;
  const open = SRC[i];
  const close = open === "{" ? "}" : open === "[" ? "]" : null;
  if (!close) throw new Error(`${name} is not an object/array literal`);
  let depth = 0, inStr = null, esc = false;
  for (let k = i; k < SRC.length; k++) {
    const c = SRC[k];
    if (esc) { esc = false; continue; }
    if (inStr) {
      if (c === "\\") esc = true;
      else if (c === inStr) inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") { inStr = c; continue; }
    if (c === "/" && SRC[k + 1] === "*") { k = SRC.indexOf("*/", k + 2) + 1; continue; }
    if (c === open) depth++;
    else if (c === close) { depth--; if (depth === 0) return SRC.slice(i, k + 1); }
  }
  throw new Error(`unterminated literal: ${name}`);
}

/** Evaluate a literal in a sandbox. Free identifiers inside closures are fine —
 *  the closures are never invoked, only stringified. */
function evalLiteral(name) {
  const ctx = vm.createContext({ Math, Object, Store: { get: () => 0, set: () => {} } });
  return vm.runInContext(`(${literalOf(name)})`, ctx, { filename: `${name}.js` });
}

/** Scalar `const NAME = 123` (supports comma-chained declarations). */
function scalars(...names) {
  const out = {};
  for (const n of names) {
    const m = new RegExp(`\\b${n}\\s*=\\s*(-?[0-9.]+)`).exec(SRC);
    if (!m) { warn(`scalar not found: ${n}`); continue; }
    out[n] = Number(m[1]);
  }
  return out;
}

/** Serialize, turning functions into { __fn } so closure logic survives to the port. */
const fnAware = (_k, v) =>
  typeof v === "function" ? { __fn: v.toString().replace(/\s+/g, " ").trim() } : v;

function write(rel, data) {
  const p = join(OUT, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, JSON.stringify(data, fnAware, 2) + "\n", "utf8");
  const n = Array.isArray(data) ? data.length : Object.keys(data).length;
  console.log(`  → ${rel} (${n} entries)`);
}

/** docs/relics-cut.md — the triage record required by Phase 0 of the port plan. */
function writeCutDoc(cut) {
  const rows = cut.map((r) =>
    `### ${r.n}  \`${r.id}\`\n\n` +
    `> ${r.fl || ""}\n\n` +
    `**Card text.** ${r.d}\n\n` +
    (r.pas ? `**Passive.** ${r.pas}\n\n` : "") +
    (r.nat ? `**Native trigger.** ${r.nat}\n\n` : "") +
    (r.act ? `**On activation.** ${r.act}\n\n` : "") +
    `**Live references** — combat engine: ${r.engineRefs} · stat ledger: ${r.ledgerRefs} · whole file: ${r.totalRefs}\n`
  ).join("\n---\n\n");
  const inEngine = cut.filter((r) => r.engineRefs > 0).length;
  const inLedger = cut.filter((r) => r.engineRefs === 0 && r.ledgerRefs > 0).length;
  const elsewhere = cut.filter((r) => r.engineRefs === 0 && r.ledgerRefs === 0 && r.totalRefs > 1).length;

  const doc =
`# Cut relics — triage record

Generated by \`Tools/extract/extract.mjs\`. Do not edit by hand.

These **${cut.length}** relics have finished card text in \`NEWR\` and live code paths behind them
— ${inEngine} in the combat engine, ${inLedger} in the stat ledger, ${elsewhere} in run/UI code — but they are
**absent from \`ITEMS\`**, the table that defines the draft pool. Nothing can ever offer
them, so no player has ever held one and none has been playtested.

Per the locked decision in [port-plan.md](port-plan.md), they are **cut from the port**:
the 50 reachable relics ship, and these are recorded here so any of them can be
reintroduced deliberately rather than by accident.

**To reintroduce one:** add an \`ITEMS\` entry (kind, emits/reacts, modes, stack), assign a
cell in \`assets/relic-icons.png\`, add its text to all 8 locales, then port its effect. It
is new content that needs balancing, not a restoration.

---

${rows}
`;
  const p = join(ROOT, "docs", "relics-cut.md");
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, doc, "utf8");
  console.log(`  → docs/relics-cut.md (${cut.length} relics)`);
}

